#!/usr/bin/env python3
"""生成 src/Tui/Services/TerminalWidthProbe.Ambiguous.g.cs（Unicode EAW=A 区间表）。

数据源：Python 标准库 unicodedata（随 Python 版本携带的 UCD），不做手工维护。
用法：python3 scripts/gen-ambiguous-table.py
"""
import pathlib
import unicodedata

ranges = []
start = prev = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    try:
        w = unicodedata.east_asian_width(chr(cp))
    except ValueError:
        continue
    if w == 'A':
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
if start is not None:
    ranges.append((start, prev))

lines = []
for s, e in ranges:
    lines.append(f"        (0x{s:04X}, 0x{s:04X})," if s == e else f"        (0x{s:04X}, 0x{e:04X}),")

content = f"""// <auto-generated>
// 由 Python unicodedata (Unicode {unicodedata.unidata_version}, east_asian_width == 'A') 生成，勿手改。
// 重新生成：scripts/gen-ambiguous-table.py
// </auto-generated>
namespace Tui.Services;

public static partial class TerminalWidthProbe
{{
    /// <summary>Unicode East_Asian_Width = Ambiguous 的码点区间（升序、不相交）。</summary>
    private static readonly (int Start, int End)[] AmbiguousRanges =
    [
{chr(10).join(lines)}
    ];
}}
"""
out = pathlib.Path(__file__).resolve().parent.parent / "src/Tui/Services/TerminalWidthProbe.Ambiguous.g.cs"
out.write_text(content, encoding="utf-8")
print(f"{out} 共 {len(ranges)} 个区间 (Unicode {unicodedata.unidata_version})")
