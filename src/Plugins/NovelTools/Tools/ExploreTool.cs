using System.ComponentModel;
using System.Text;
using ClientPlatform;
using Core.Agent;
using Core.Data;
using Core.Shared;
using Core.Tools;
using LlmTornado;
using LlmTornado.Chat;
using LlmTornado.Chat.Vendors.Anthropic;
using LlmTornado.Code;

namespace Plugins.NovelTools.Tools;

/// <summary>
/// 并行探索工具 — 同时生成 N 个变体，供用户比较选择。
/// Tool 内部发起 N 个并行 LLM API 调用，每个调用使用相同上下文快照但不同的方向指令。
/// </summary>
public sealed class ExploreTool(Agent agent, INovelStore store)
    : AgentTool<ExploreParams, ExploreDetails>
{
    public override string Name => "explore";
    public override string Label => "并行探索";
    public override string Description =>
        "并行探索多个创作方向。同时生成 N 个变体（默认3个，最多5个），"
        + "每个变体使用相同上下文但不同的方向指令。"
        + "支持大纲、人物、情节、风格、重写等探索类型。"
        + "用户可比较后选择最佳变体。";
    public override ToolCategory Category => ToolCategory.Generic;

    // 长耗时 + 读 store 上下文快照：串行避免与同轮写入工具并发读到半新状态
    public override ToolExecutionMode ExecutionMode => ToolExecutionMode.Sequential;

    public override async Task<AgentToolResult<ExploreDetails>> ExecuteAsync(
        string toolCallId,
        ExploreParams args,
        CancellationToken ct,
        IProgress<AgentToolResult<ExploreDetails>>? onUpdate = null
    )
    {
        ThrowIfCancelled(ct);

        // 参数校验
        if (string.IsNullOrEmpty(args.Prompt))
            return new AgentToolResult<ExploreDetails>
            {
                Content = [new TextContent("请提供探索提示（prompt）")],
                IsError = true,
            };

        var api = agent.TornadoApi;
        if (api is null)
            return new AgentToolResult<ExploreDetails>
            {
                Content = [new TextContent("无法生成变体：未配置 LLM API")],
                IsError = true,
            };

        // 确定方向列表
        var directions =
            args.Directions?.Count > 0
                ? args.Directions.Take(Math.Min(args.Count, 5)).ToList()
                : AutoGenerateDirections(args.Prompt, args.ExploreType, args.Count);

        directions = directions.Take(Math.Min(args.Count, 5)).ToList();
        if (directions.Count == 0)
            return new AgentToolResult<ExploreDetails>
            {
                Content = [new TextContent("无法生成变体：方向列表为空")],
                IsError = true,
            };

        // 获取当前上下文快照
        var state = agent.State;
        var systemPrompt = state.SystemPrompt;
        var modelName = state.ModelName;
        var historicalMessages = state.Messages;

        // 报告开始
        onUpdate?.Report(
            new AgentToolResult<ExploreDetails>
            {
                Content = [new TextContent($"正在并行生成 {directions.Count} 个变体…")],
            }
        );

        // 并行生成变体
        var tasks = directions.Select(
            async (dir, i) =>
            {
                ThrowIfCancelled(ct);

                var conversation = CreateExploreConversation(api, modelName, systemPrompt);

                // 注入历史消息（跳过 system message，因为 Conversation 已有）
                foreach (var msg in historicalMessages)
                {
                    switch (msg.Role)
                    {
                        case ChatMessageRoles.System:
                        case ChatMessageRoles.Unknown:
                            continue;
                        default:
                            conversation.AddMessage(msg);
                            break;
                    }
                }

                // 注入方向指令
                var directionPrompt = BuildDirectionPrompt(
                    i + 1,
                    dir,
                    args.Prompt,
                    args.ExploreType
                );
                conversation.AddUserMessage(directionPrompt);

                var variantId = Guid.NewGuid().ToString("N")[..12];
                using var timeoutCts = CancellationTokenSource.CreateLinkedTokenSource(ct);
                timeoutCts.CancelAfter(CloudTimings.AuxiliaryLlmTimeout);
                try
                {
                    var sb = new StringBuilder();
                    await foreach (
                        var chunk in conversation.StreamResponseEnumerable(token: timeoutCts.Token)
                    )
                        sb.Append(chunk);
                    var response = sb.ToString();
                    return new VariantResult
                    {
                        Id = variantId,
                        Label = dir,
                        Description = dir,
                        Content = string.IsNullOrWhiteSpace(response)
                            ? "（生成失败）"
                            : response.Trim(),
                    };
                }
                catch (OperationCanceledException) when (ct.IsCancellationRequested)
                {
                    throw;
                }
                catch (OperationCanceledException)
                {
                    return new VariantResult
                    {
                        Id = variantId,
                        Label = dir,
                        Description = dir,
                        Content = "（生成超时）",
                        IsFailed = true,
                    };
                }
                catch (Exception ex)
                {
                    return new VariantResult
                    {
                        Id = variantId,
                        Label = dir,
                        Description = dir,
                        Content = $"（生成失败: {ex.Message}）",
                        IsFailed = true,
                    };
                }
            }
        );

        var variants = await Task.WhenAll(tasks);

        // 构建结果摘要
        var summary = new StringBuilder();
        summary.AppendLine($"已生成 {variants.Length} 个变体：\n");
        for (var i = 0; i < variants.Length; i++)
        {
            var v = variants[i];
            var preview = v.Content.Truncate(100);
            summary.AppendLine($"**{i + 1}. {v.Label}**");
            summary.AppendLine(preview);
            summary.AppendLine();
        }
        summary.AppendLine("请在 UI 中选择一个变体，或按 Esc 放弃所有变体。");

        var novelId = agent.CurrentNovelId ?? "";
        VariantApplyTarget? applyTarget = null;

        if (!string.IsNullOrWhiteSpace(args.ChapterId))
        {
            // 从 store 查出章节真实 Title/Order，不依赖 LLM 传参
            var chapters = await store.GetChapters(novelId, ct);
            var chapter =
                chapters.FirstOrDefault(c => c.Id == args.ChapterId)
                ?? chapters.FirstOrDefault(c => c.Order.ToString() == args.ChapterId);
            applyTarget = chapter is not null
                ? new VariantApplyTarget
                {
                    NovelId = novelId,
                    ChapterId = chapter.Id,
                    Title = chapter.Title,
                    Order = chapter.Order,
                }
                : new VariantApplyTarget
                {
                    NovelId = novelId,
                    ChapterId = args.ChapterId,
                    Title = args.ChapterTitle ?? "",
                    Order = args.ChapterOrder ?? 0,
                };
        }
        else if (args is { ChapterTitle: not null, ChapterOrder: not null })
        {
            applyTarget = new VariantApplyTarget
            {
                NovelId = novelId,
                Title = args.ChapterTitle,
                Order = args.ChapterOrder.Value,
            };
        }

        return new AgentToolResult<ExploreDetails>
        {
            Content = [new TextContent(summary.ToString())],
            Details = new ExploreDetails
            {
                VariantSetId = Guid.NewGuid().ToString("N")[..12],
                ExploreType = args.ExploreType,
                Prompt = args.Prompt,
                Variants = variants.ToList(),
                ApplyTarget = applyTarget,
            },
            Terminate = true,
        };
    }

    /// <summary>
    /// 创建用于探索的独立 Conversation。
    /// </summary>
    private static Conversation CreateExploreConversation(
        TornadoApi api,
        string modelName,
        string systemPrompt
    )
    {
        var request = new ChatRequest
        {
            Model = modelName,
            ReasoningFormat = ChatReasoningFormats.Parsed,
            // 配置思考级别（使用 medium 作为探索默认值）
            ReasoningEffort = ChatReasoningEfforts.Medium,
            VendorExtensions = new ChatRequestVendorExtensions(
                new ChatRequestVendorAnthropicExtensions
                {
                    Thinking = new AnthropicThinkingSettings
                    {
                        BudgetTokens = 8192,
                        Enabled = true,
                    },
                }
            ),
        };

        var conversation = api.Chat.CreateConversation(request);
        conversation.AddSystemMessage(
            string.IsNullOrEmpty(systemPrompt)
                ? "你是一个小说创作助手。请根据用户指定的方向进行创作探索。"
                : systemPrompt
        );

        return conversation;
    }

    /// <summary>
    /// 构建方向注入提示。
    /// </summary>
    private static string BuildDirectionPrompt(
        int index,
        string direction,
        string prompt,
        string exploreType
    )
    {
        var typeHint = exploreType switch
        {
            "outline" => "大纲",
            "character" => "人物",
            "plot" => "情节",
            "style" => "风格",
            "rewrite" => "重写",
            _ => "创作",
        };

        return $"【探索方向{index}: {direction}】\n"
            + $"探索类型: {typeHint}\n"
            + $"{prompt}\n"
            + $"请按照「{direction}」的方向来创作。"
            + "直接输出创作内容，不要重复方向说明。";
    }

    /// <summary>
    /// 自动生成探索方向（当用户未指定方向时）。
    /// </summary>
    private static List<string> AutoGenerateDirections(string prompt, string exploreType, int count)
    {
        var clampedCount = Math.Clamp(count, 2, 5);

        return exploreType switch
        {
            "plot" => clampedCount switch
            {
                2 => ["悬疑向", "温情向"],
                3 => ["悬疑向", "温情向", "史诗向"],
                4 => ["悬疑向", "温情向", "史诗向", "反转向"],
                _ => ["悬疑向", "温情向", "史诗向", "反转向", "哲思向"],
            },
            "style" => clampedCount switch
            {
                2 => ["细腻抒情", "简洁有力"],
                3 => ["细腻抒情", "简洁有力", "诗意象征"],
                4 => ["细腻抒情", "简洁有力", "诗意象征", "黑色幽默"],
                _ => ["细腻抒情", "简洁有力", "诗意象征", "黑色幽默", "意识流"],
            },
            "character" => clampedCount switch
            {
                2 => ["内敛深沉", "外放张扬外放"],
                3 => ["内敛深沉", "张扬外放", "矛盾复杂"],
                4 => ["内敛深沉", "张扬外放", "矛盾复杂", "亦正亦邪"],
                _ => ["内敛深沉", "张扬外放", "矛盾复杂", "亦正亦邪", "天真纯粹"],
            },
            "outline" => clampedCount switch
            {
                2 => ["线性叙事", "多线交织"],
                3 => ["线性叙事", "多线交织", "倒叙揭秘"],
                4 => ["线性叙事", "多线交织", "倒叙揭秘", "环形结构"],
                _ => ["线性叙事", "多线交织", "倒叙揭秘", "环形结构", "碎片化叙事"],
            },
            "rewrite" => clampedCount switch
            {
                2 => ["精简版", "扩写版"],
                3 => ["精简版", "扩写版", "风格转换版"],
                4 => ["精简版", "扩写版", "风格转换版", "视角转换版"],
                _ => ["精简版", "扩写版", "风格转换版", "视角转换版", "深度挖掘版"],
            },
            // 默认
            _ => clampedCount switch
            {
                2 => ["方案A", "方案B"],
                3 => ["方案A", "方案B", "方案C"],
                4 => ["方案A", "方案B", "方案C", "方案D"],
                _ => ["方案A", "方案B", "方案C", "方案D", "方案E"],
            },
        };
    }
}

public sealed record ExploreParams
{
    [Description("探索提示：描述要探索的内容和方向")]
    public string Prompt { get; init; } = "";

    [Description("探索方向列表，每个方向生成一个变体。留空则自动生成方向")]
    public List<string>? Directions { get; init; }

    [Description("变体数量，默认 3，最大 5")]
    public int Count { get; init; } = 3;

    [Description(
        "探索类型：outline（大纲）、character（人物）、plot（情节）、style（风格）、rewrite（重写）"
    )]
    public string ExploreType { get; init; } = "style";

    [Description("目标章节ID。提供后变体可被应用为章节，留空则变体仅用于对话")]
    public string? ChapterId { get; init; }

    [Description("章节标题（新建或覆盖时使用）")]
    public string? ChapterTitle { get; init; }

    [Description("章节序号（新建时使用）")]
    public int? ChapterOrder { get; init; }
}
